"""Build a LoRA training set from the RAG corpus.

The goal of the adapter is *style and format compliance*, not new knowledge:
short, grounded, citation-carrying answers in the language of the question. So
every training example is a full prompt/answer pair rendered with the same
versioned prompt the service uses at inference time — a mismatch between the
training format and the serving format is the fastest way to make an adapter
useless.

Examples are produced from the corpus in two ways:

* ``grounded``  - question + the chunk that answers it + a cited answer;
* ``refusal``   - question + unrelated chunks + the exact refusal sentence,
  which is what teaches the model not to answer from parametric memory.

Usage:
    python finetune/prepare_dataset.py --corpus data/corpus --out data/finetune
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

from voicerag.prompts.registry import PromptRegistry
from voicerag.rag.chunking import chunk_documents
from voicerag.rag.documents import Chunk
from voicerag.rag.loaders import load_directory
from voicerag.rag.pipeline import REFUSAL

OUT_OF_DOMAIN_QUESTIONS = [
    "What is the capital of Australia?",
    "How do I renew my driver's licence?",
    "Who won the 2022 World Cup?",
    "What is the price of the OpenAI API?",
    "Скільки коштує квиток до Львова?",
    "Яка погода буде завтра?",
]


def question_from_chunk(chunk: Chunk) -> str:
    """Derive a question from the chunk's heading path.

    Heading-derived questions are weak supervision, but they are consistent and
    cheap. For a real adapter, replace this with questions written by hand or
    generated by a stronger model and then reviewed — see docs/EXPERIMENTS.md.
    """
    heading = str(chunk.metadata.get("heading", "")).split(" > ")[-1].strip()
    return (
        f"What does the handbook say about {heading.lower()}?"
        if heading
        else "Summarise this section."
    )


def answer_from_chunk(chunk: Chunk, source_index: int = 1) -> str:
    sentences = [s.strip() for s in chunk.text.split(". ") if len(s.strip()) > 30]
    body = ". ".join(sentences[:2]).rstrip(".")
    return f"{body}. [S{source_index}]"


def build_examples(
    chunks: list[Chunk],
    registry: PromptRegistry,
    prompt_ref: str,
    n_distractors: int,
    seed: int,
) -> list[dict]:
    rng = random.Random(seed)
    template = registry.get(prompt_ref)
    examples: list[dict] = []

    for chunk in chunks:
        distractors = rng.sample(
            [c for c in chunks if c.chunk_id != chunk.chunk_id],
            k=min(n_distractors, len(chunks) - 1),
        )
        context = [chunk, *distractors]
        rng.shuffle(context)
        gold_index = context.index(chunk) + 1
        question = question_from_chunk(chunk)
        messages = template.render(
            question=question,
            chunks=[{"source": c.source, "text": c.text} for c in context],
        )
        examples.append(
            {
                "type": "grounded",
                "messages": [m.as_dict() for m in messages]
                + [{"role": "assistant", "content": answer_from_chunk(chunk, gold_index)}],
                "meta": {
                    "source": chunk.source,
                    "prompt": template.ref,
                    "prompt_sha": template.sha256,
                },
            }
        )

    for question in OUT_OF_DOMAIN_QUESTIONS:
        context = rng.sample(chunks, k=min(n_distractors + 1, len(chunks)))
        messages = template.render(
            question=question,
            chunks=[{"source": c.source, "text": c.text} for c in context],
        )
        examples.append(
            {
                "type": "refusal",
                "messages": [m.as_dict() for m in messages]
                + [{"role": "assistant", "content": REFUSAL}],
                "meta": {"source": "-", "prompt": template.ref, "prompt_sha": template.sha256},
            }
        )

    rng.shuffle(examples)
    return examples


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", type=Path, default=Path("data/corpus"))
    parser.add_argument("--out", type=Path, default=Path("data/finetune"))
    parser.add_argument("--prompts", type=Path, default=Path("prompts"))
    parser.add_argument("--prompt-ref", default="rag_answer@latest")
    parser.add_argument("--chunk-size", type=int, default=800)
    parser.add_argument("--chunk-overlap", type=int, default=120)
    parser.add_argument("--distractors", type=int, default=3)
    parser.add_argument("--eval-fraction", type=float, default=0.15)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    documents = load_directory(args.corpus)
    chunks = chunk_documents(documents, args.chunk_size, args.chunk_overlap)
    registry = PromptRegistry(args.prompts)
    examples = build_examples(chunks, registry, args.prompt_ref, args.distractors, args.seed)

    split = max(1, int(len(examples) * args.eval_fraction))
    eval_rows, train_rows = examples[:split], examples[split:]

    args.out.mkdir(parents=True, exist_ok=True)
    for name, rows in (("train", train_rows), ("eval", eval_rows)):
        path = args.out / f"{name}.jsonl"
        with path.open("w", encoding="utf-8") as fh:
            for row in rows:
                fh.write(json.dumps(row, ensure_ascii=False) + "\n")
        kinds = {t: sum(1 for r in rows if r["type"] == t) for t in {r["type"] for r in rows}}
        print(f"{path}: {len(rows)} examples {kinds}")

    print(
        "\nNOTE: heading-derived questions are weak supervision. Review "
        f"{args.out}/train.jsonl before training an adapter you intend to ship."
    )


if __name__ == "__main__":
    main()
